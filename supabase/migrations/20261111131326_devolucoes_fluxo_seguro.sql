CREATE OR REPLACE FUNCTION public.hh_notificar_troca() RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
DECLARE payload jsonb;
BEGIN
  IF TG_OP='UPDATE' AND NEW.status IS NOT DISTINCT FROM OLD.status AND NEW.codigo_postagem IS NOT DISTINCT FROM OLD.codigo_postagem THEN RETURN NEW; END IF;
  payload := jsonb_build_object('pedidoId',NEW.pedido_id,'status',NEW.status,'produto',NEW.produto_snapshot,'codigo',NEW.codigo_postagem,
    'validade',NEW.postagem_validade,'observacao',NEW.observacao_cliente,'resolucao',NEW.resolucao,'credito',NEW.credito_valor);
  INSERT INTO public.troca_notificacoes(troca_id,versao,destinatario,payload) VALUES(NEW.id,NEW.versao,'cliente',payload) ON CONFLICT DO NOTHING;
  IF TG_OP='INSERT' THEN
    INSERT INTO public.troca_notificacoes(troca_id,versao,destinatario,payload) VALUES(NEW.id,NEW.versao,'admin',payload) ON CONFLICT DO NOTHING;
  END IF;
  RETURN NEW;
END $$;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgrelid='public.trocas'::regclass AND tgname='hh_notificar_troca') THEN
    CREATE TRIGGER hh_notificar_troca AFTER INSERT OR UPDATE ON public.trocas FOR EACH ROW EXECUTE FUNCTION public.hh_notificar_troca();
  END IF;
END $$;

CREATE OR REPLACE FUNCTION public.hh_claim_troca_notificacoes(p_limite integer DEFAULT 10)
RETURNS SETOF public.troca_notificacoes LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
BEGIN
  RETURN QUERY UPDATE public.troca_notificacoes n SET status='processando',lease_id=gen_random_uuid(),locked_until=now()+interval '2 minutes',tentativas=n.tentativas+1
    WHERE n.id IN (SELECT q.id FROM public.troca_notificacoes q WHERE (q.status='pendente' AND q.disponivel_em<=now()) OR (q.status='processando' AND q.locked_until<now())
      ORDER BY q.id FOR UPDATE SKIP LOCKED LIMIT least(greatest(p_limite,1),20)) RETURNING n.*;
END $$;

CREATE OR REPLACE FUNCTION public.hh_claim_reversa(p_troca_id uuid,p_lease uuid,p_ambiente text,p_config jsonb DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
DECLARE t public.trocas;
BEGIN
  SELECT * INTO t FROM public.trocas WHERE id=p_troca_id FOR UPDATE;
  IF NOT FOUND OR t.status NOT IN ('aprovado','aguardando_retorno') THEN RAISE EXCEPTION 'Aprove a solicitacao antes de gerar a reversa'; END IF;
  IF t.reversa_lock_until>now() THEN RAISE EXCEPTION 'Reversa em processamento'; END IF;
  IF p_ambiente NOT IN ('production','sandbox') OR (t.reversa<>'{}' AND t.reversa->>'ambiente' IS DISTINCT FROM p_ambiente) THEN RAISE EXCEPTION 'Ambiente da reversa incompativel'; END IF;
  IF t.reversa='{}' OR t.reversa->>'estado'='nova' THEN
    IF p_config IS NULL THEN RAISE EXCEPTION 'Consulte o frete reverso antes de continuar'; END IF;
    t.reversa := jsonb_build_object('estado','nova','ambiente',p_ambiente,'config',p_config);
  END IF;
  UPDATE public.trocas SET reversa=t.reversa,reversa_lease=p_lease,reversa_lock_until=now()+interval '2 minutes' WHERE id=p_troca_id RETURNING * INTO t;
  RETURN to_jsonb(t);
END $$;

CREATE OR REPLACE FUNCTION public.hh_creditar_devolucao(p_troca_id uuid,p_valor numeric,p_observacao text)
RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
DECLARE t public.trocas; p public.pedidos; email_cliente text; limite numeric; recompensa numeric; reversao numeric;
BEGIN
  SELECT u.email INTO email_cliente FROM public.trocas x JOIN public.usuarios u ON u.id=x.usuario_id WHERE x.id=p_troca_id;
  PERFORM 1 FROM public.usuarios WHERE email=email_cliente FOR UPDATE;
  SELECT * INTO p FROM public.pedidos WHERE id::text=(SELECT pedido_id FROM public.trocas WHERE id=p_troca_id) FOR UPDATE;
  SELECT * INTO t FROM public.trocas WHERE id=p_troca_id FOR UPDATE;
  IF t.credito_liberado_em IS NOT NULL THEN RETURN to_jsonb(t); END IF;
  IF t.status<>'recebido' OR t.recebido_em IS NULL OR t.resolucao<>'credito' OR t.credito_aceito_em IS NULL OR p.cliente_email IS DISTINCT FROM email_cliente THEN RAISE EXCEPTION 'Credito exige recebimento e escolha expressa do cliente'; END IF;
  IF p.pagamento->>'status' IN ('refunded','charged_back','in_mediation') OR coalesce((p.pagamento->>'valor_reembolsado')::numeric,0)>0 THEN RAISE EXCEPTION 'Pagamento possui estorno ou contestacao; concilie antes de creditar'; END IF;
  limite := least(coalesce((t.produto_snapshot->>'valor_restituicao')::numeric,(t.produto_snapshot->>'preco')::numeric*(t.produto_snapshot->>'quantidade')::numeric),p.total+p.cashback_debitado-p.devolvido_credito);
  IF limite IS NULL OR p_valor IS NULL OR p_valor<=0 OR p_valor<>round(p_valor,2) OR p_valor>limite OR ((t.produto_snapshot->>'valor_restituicao') IS NOT NULL AND p_valor<>(t.produto_snapshot->>'valor_restituicao')::numeric) THEN RAISE EXCEPTION 'Valor de credito incompativel com o pedido'; END IF;
  IF t.produto_snapshot->>'valor_restituicao' IS NULL AND length(trim(coalesce(p_observacao,'')))<10 THEN RAISE EXCEPTION 'Pedido antigo exige conferencia e justificativa do valor pago'; END IF;
  recompensa := CASE WHEN p.cashback_creditado_em IS NOT NULL THEN round(p.total*0.05,2) ELSE 0 END;
  reversao := greatest(0,least(recompensa-p.cashback_revertido,round(recompensa*p_valor/nullif(p.total+p.cashback_debitado,0),2)));
  UPDATE public.usuarios SET saldo_cashback=coalesce(saldo_cashback,0)+p_valor-reversao WHERE email=email_cliente;
  UPDATE public.pedidos SET devolvido_credito=devolvido_credito+p_valor,cashback_revertido=cashback_revertido+reversao WHERE id=p.id;
  UPDATE public.trocas SET status='concluido',credito_valor=p_valor,credito_liberado_em=now(),finalizado_em=now(),observacao_cliente=p_observacao,versao=versao+1 WHERE id=t.id RETURNING * INTO t;
  RETURN to_jsonb(t);
END $$;

