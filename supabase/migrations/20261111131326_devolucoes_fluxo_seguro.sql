-- O resumo financeiro e o pedido são gravados na mesma transação do checkout.
CREATE OR REPLACE FUNCTION public.hh_checkout_com_resumo(p_email text,p_nome text,p_total numeric,p_itens jsonb,p_cashback numeric,p_entrega jsonb,p_frete jsonb,p_chave uuid,p_hash text,p_resumo jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
DECLARE resultado jsonb;
BEGIN
  IF jsonb_typeof(p_resumo) IS DISTINCT FROM 'object' OR (p_resumo->>'total')::numeric IS DISTINCT FROM p_total THEN RAISE EXCEPTION 'Resumo financeiro invalido'; END IF;
  resultado := public.hh_checkout_seguro(p_email,p_nome,p_total,p_itens,p_cashback,p_entrega,p_frete,p_chave,p_hash);
  UPDATE public.pedidos SET resumo_compra=coalesce(resumo_compra,p_resumo) WHERE id::text=resultado->>'id' RETURNING to_jsonb(pedidos.*) INTO resultado;
  RETURN resultado;
END $$;

CREATE OR REPLACE FUNCTION public.hh_registrar_reembolso_devolucao(p_troca_id uuid,p_valor numeric,p_referencia text)
RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
DECLARE t public.trocas; p public.pedidos; registrado numeric; disponivel numeric; limite numeric;
BEGIN
  SELECT * INTO p FROM public.pedidos WHERE id::text=(SELECT pedido_id FROM public.trocas WHERE id=p_troca_id) FOR UPDATE;
  SELECT * INTO t FROM public.trocas WHERE id=p_troca_id FOR UPDATE;
  IF t.reembolso_referencia IS NOT NULL THEN RETURN to_jsonb(t); END IF;
  IF t.status NOT IN ('recebido','reembolso_pendente') OR t.resolucao<>'reembolso' OR t.recebido_em IS NULL OR length(trim(p_referencia))<3 THEN RAISE EXCEPTION 'Reembolso exige recebimento e referencia do provedor'; END IF;
  SELECT coalesce(sum(reembolso_valor),0) INTO registrado FROM public.trocas WHERE pedido_id=t.pedido_id;
  disponivel := coalesce((p.pagamento->>'valor_reembolsado')::numeric,0)-registrado;
  limite := least(p.total,coalesce((t.produto_snapshot->>'valor_restituicao')::numeric,(t.produto_snapshot->>'preco')::numeric*(t.produto_snapshot->>'quantidade')::numeric));
  IF limite IS NULL OR p_valor IS NULL OR p_valor<=0 OR p_valor<>round(p_valor,2) OR p_valor>limite OR p_valor>disponivel THEN RAISE EXCEPTION 'O valor ainda nao foi confirmado como estornado pelo provedor'; END IF;
  UPDATE public.trocas SET status='concluido',reembolso_referencia=p_referencia,reembolso_valor=p_valor,finalizado_em=now(),versao=versao+1,
    observacao_cliente='Reembolso confirmado pelo provedor. O prazo de disponibilidade depende do meio de pagamento.' WHERE id=t.id RETURNING * INTO t;
  RETURN to_jsonb(t);
END $$;

CREATE TABLE IF NOT EXISTS public.troca_notificacoes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  troca_id uuid NOT NULL REFERENCES public.trocas(id),
  versao integer NOT NULL,
  destinatario text NOT NULL CHECK (destinatario IN ('cliente','admin')),
  payload jsonb NOT NULL,
  status text NOT NULL DEFAULT 'pendente',
  tentativas integer NOT NULL DEFAULT 0,
  disponivel_em timestamptz NOT NULL DEFAULT now(),
  locked_until timestamptz,
  lease_id uuid,
  enviada_em timestamptz,
  UNIQUE(troca_id,versao,destinatario)
);
